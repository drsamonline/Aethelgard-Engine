#!/usr/bin/env python3
"""
Import AI-generated sprite art into an Aethelgard graphics pack.

Use this with images generated by a design tool (e.g. Runway) that you
have saved to disk. It:

  1. reads every .png/.jpg/.webp in the input folder,
  2. removes the flat background (chroma-key on the corner colour),
  3. trims to the subject and pads to a square,
  4. resizes to 256px and writes mods/ai-art/sprites/,
  5. generates mods/ai-art/mod.js listing every sprite.

Name each file after the sprite key it should fill, using underscores:

    enemy_wolf.png      ->  "enemy.wolf"
    class_mage.png      ->  "class.mage"
    item_potion.png     ->  "item.potion"
    loc_oakhaven.png    ->  "loc.oakhaven"

Usage:
    python3 tools/import-ai-art.py <folder-with-images>
    python3 tools/import-ai-art.py <folder> --pack-id my-art --name "My Art"
"""
import argparse
import pathlib
import sys

try:
    from PIL import Image, ImageFilter
except ImportError:
    sys.exit("Pillow is required: pip install pillow")
try:
    import numpy as np
except ImportError:
    np = None

ROOT = pathlib.Path(__file__).resolve().parent.parent

# keys the game understands; a filename maps to one of these
KNOWN_PREFIXES = ("enemy", "class", "race", "player", "item", "gear", "loc",
                  "poi", "companion", "status", "skill", "gem", "set", "bld", "ach", "ending", "bg")

# keys that are full-scene backgrounds: resized, never cut out
BG_KEYS = {"bg.oakhaven", "bg.mire", "bg.cave", "bg.mountains", "bg.temple", "bg.ruins",
           "bg.banditcamp", "bg.depths", "bg.title", "bg.world", "bg.combat"}

# filenames whose underscores are PART of the id, not a separator
MULTIWORD_IDS = {
    "rogue_mage", "hand_axe", "hunting_bow", "steel_sword", "runic_blade", "twin_dagger",
    "arcane_staff", "iron_plate", "leather_armor", "dragonscale", "iron_helm", "swift_boots",
    "ruby_ring", "guardian_amulet", "sister_maeve", "bog_horror", "spider_queen",
}


def key_from_filename(stem):
    """enemy_rogue_mage -> enemy.rogue_mage  |  class_mage -> class.mage

    Points of interest carry a region as well, and the game looks them up as
    poi.<region>.<id>, so poi_hollowmere_hm_ice -> poi.hollowmere.hm_ice.
    """
    if stem.startswith("poi_"):
        parts = stem.split("_")
        if len(parts) >= 3:
            return "poi." + parts[1] + "." + "_".join(parts[2:])
        return None
    for pref in KNOWN_PREFIXES:
        if stem.startswith(pref + "_"):
            rest = stem[len(pref) + 1:]
            return f"{pref}.{rest}"
    return None


def remove_flat_bg(img, tol=48, extra_keys=()):
    """Cut the background out, coping with a *gradient* background.

    Generators often paint a magenta backdrop that fades from bright to dark.
    So instead of one key colour, every colour found in a thin border ring is
    treated as background — which handles flat, graded and vignetted plates
    alike. `extra_keys` adds further colours (a second panel, say).
    """
    img = img.convert("RGBA")
    if np is None:                                   # pure-PIL fallback
        w, h = img.size
        px = img.load()
        corners = [px[0, 0], px[w-1, 0], px[0, h-1], px[w-1, h-1]]
        bg = max(set(corners), key=corners.count)
        keys = [bg] + [tuple(k) for k in extra_keys]
        out = Image.new("RGBA", (w, h), (0, 0, 0, 0)); op = out.load()
        for y in range(h):
            for x in range(w):
                r, g, b, a = px[x, y]
                d = min(abs(r-k[0]) + abs(g-k[1]) + abs(b-k[2]) for k in keys)
                op[x, y] = (r, g, b, 0) if d <= tol else (r, g, b, a)
        return out

    rgb = np.asarray(img.convert("RGB")).astype(np.int16)
    h, w = rgb.shape[:2]

    # Work the mask out at a reduced scale — a lot faster, and the result is
    # upscaled at the end.
    sc = max(1.0, max(w, h) / 512.0)
    sw, sh = max(1, int(w / sc)), max(1, int(h / sc))
    small = np.asarray(img.convert("RGB").resize((sw, sh), Image.LANCZOS)).astype(np.int16)

    band = max(2, min(sw, sh) // 40)
    border = np.zeros((sh, sw), bool)
    border[:band, :] = border[-band:, :] = True
    border[:, :band] = border[:, -band:] = True

    q = (small // 16) * 16
    enc = (q[..., 0].astype(np.int32) << 16) | (q[..., 1].astype(np.int32) << 8) | q[..., 2].astype(np.int32)
    vals = np.unique(enc[border])
    for k in extra_keys:
        kk = [(int(v) // 16) * 16 for v in k]
        vals = np.append(vals, (kk[0] << 16) | (kk[1] << 8) | kk[2])

    seed = np.isin(enc, vals)

    # Grow the background through *smooth* transitions only, so a gradient or a
    # glow behind the subject is absorbed, but a hard subject edge stops it.
    # only spread through true magenta/pink — never through violet, blue or
    # red subjects that happen to sit near the background
    r_, g_, b_ = small[..., 0], small[..., 1], small[..., 2]
    mag = (r_ > g_ + 25) & (b_ > g_ + 25) & (r_ > b_ - 50)

    T = 50
    du = np.abs(small - np.roll(small, 1, 0)).sum(-1)
    dd = np.abs(small - np.roll(small, -1, 0)).sum(-1)
    dl = np.abs(small - np.roll(small, 1, 1)).sum(-1)
    dr = np.abs(small - np.roll(small, -1, 1)).sum(-1)
    bg = seed.copy()
    for _ in range(120):
        n = int(bg.sum())
        bg |= np.roll(bg, 1, 0) & (du < T) & mag
        bg |= np.roll(bg, -1, 0) & (dd < T) & mag
        bg |= np.roll(bg, 1, 1) & (dl < T) & mag
        bg |= np.roll(bg, -1, 1) & (dr < T) & mag
        if int(bg.sum()) == n:
            break
    # Strongly-magenta pixels go too, wherever they are — this catches a bright
    # glow sitting behind a dark figure that the fill cannot reach. The bar is
    # set high (r and b far above g) so violet subjects like an amethyst, whose
    # highlights are far less saturated, are left untouched.
    # magenta/pink has red at least as strong as blue; violet (an amethyst,
    # a purple robe) has blue clearly above red — that is the discriminator
    strong = (r_ > b_) & (r_ > g_ + 90) & (b_ > g_ + 60)
    bg |= strong

    # safety: never eat almost the whole picture
    if bg.mean() > 0.93:
        bg = seed

    m = Image.fromarray(((~bg).astype(np.uint8) * 255), "L").resize((w, h), Image.BILINEAR)
    keep = np.asarray(m) > 128
    # the mask was built on a downscaled copy, where blending dulls saturated
    # magenta — so re-test at full resolution before finalising
    rf, gf, bf = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    strong_full = (rf > bf) & (rf > gf + 90) & (bf > gf + 60)
    keep &= ~strong_full
    alpha = np.where(keep, 255, 0).astype(np.uint8)
    im = Image.fromarray(np.dstack([rgb.astype(np.uint8), alpha]), "RGBA")
    a = im.getchannel("A").filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.7))
    im.putalpha(a)
    return im


def fit_backdrop(img, w=1600, h=900):
    """Cover-crop a full-scene background to 16:9 and resize."""
    img = img.convert("RGB")
    sw, sh = img.size
    scale = max(w / sw, h / sh)
    img = img.resize((max(1, int(sw * scale)), max(1, int(sh * scale))), Image.LANCZOS)
    left = (img.width - w) // 2
    top = (img.height - h) // 2
    return img.crop((left, top, left + w, top + h))


def trim_pad(img, size=256, pad=8):
    bbox = img.getbbox()
    if bbox:
        img = img.crop(bbox)
    w, h = img.size
    scale = min((size - pad * 2) / max(1, w), (size - pad * 2) / max(1, h))
    img = img.resize((max(1, int(w * scale)), max(1, int(h * scale))), Image.LANCZOS)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.paste(img, ((size - img.width) // 2, (size - img.height) // 2), img)
    return canvas


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder", help="folder containing the generated images")
    ap.add_argument("--pack-id", default="ai-art")
    ap.add_argument("--name", default="AI Art Pack")
    ap.add_argument("--tol", type=int, default=48, help="background match tolerance")
    ap.add_argument("--size", type=int, default=256, help="output size in px for sprites (default 256)")
    ap.add_argument("--key", action="append", default=[], metavar="R,G,B",
                    help="an extra background colour to key out (repeatable)")
    args = ap.parse_args()

    src = pathlib.Path(args.folder)
    if not src.is_dir():
        sys.exit(f"Not a folder: {src}")

    pack = ROOT / "mods" / args.pack_id
    out = pack / "sprites"
    out.mkdir(parents=True, exist_ok=True)

    files = sorted([p for p in src.iterdir()
                    if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp")])
    if not files:
        sys.exit(f"No images found in {src}")

    written = []
    for f in files:
        key = key_from_filename(f.stem)
        if not key:
            print(f"  skip {f.name} (name it like enemy_wolf.png)")
            continue
        img = Image.open(f)
        if key in BG_KEYS or key.startswith("bg."):
            img = fit_backdrop(img)                      # full scene — no cutout
            name = f.stem + ".webp"                      # webp keeps the package small
            img.save(out / name, "WEBP", quality=82, method=6)
            print(f"  {f.name} -> {key}  (backdrop 1600x900 webp)")
        else:
            extra = [tuple(int(v) for v in k.split(",")) for k in args.key]
            img = remove_flat_bg(img, args.tol, extra)   # character — cut the flat bg out
            img = trim_pad(img, size=args.size)
            name = f.stem + ".png"
            img.save(out / name)
            print(f"  {f.name} -> {key}  (sprite 256x256, transparent)")
        written.append((key, name))

    if not written:
        sys.exit("Nothing imported.")

    lines = "".join(f'      "{k}": "{n}",\n' for k, n in written)
    mod = f"""/* ============================================================
   {args.name} — generated by tools/import-ai-art.py
   Select it in Settings -> Graphics pack.
   ============================================================ */
window.AETHELGARD_MODS = window.AETHELGARD_MODS || [];

window.AETHELGARD_MODS.push({{
  id: "{args.pack_id}",
  name: "{args.name}",
  version: "1.0.0",
  author: "Dr. Sohil Momin",
  description: "AI-generated sprite art imported from disk.",
  impact: "additive",
  provides: ["art:ai"],

  GRAPHICS: {{
    id: "{args.pack_id}-graphics",
    name: "{args.name}",
    base: "mods/{args.pack_id}/sprites/",
    pixel: false,
    scale: 1.3,
    sprites: {{
{lines}    }},
  }},
}});
"""
    (pack / "mod.js").write_text(mod, encoding="utf-8")
    print(f"\nImported {len(written)} sprites -> {out}")
    print(f"Wrote {pack / 'mod.js'}")
    print("Now run:  python3 tools/build-mods-index.py   then reload the game.")


if __name__ == "__main__":
    main()
